import { copyFile, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import sharp from 'sharp';

// Builds the Windows launcher and installer with the C# compiler that ships with
// Windows (.NET Framework 4.8): no SDK, no extra dependency in the project.
const run = promisify(execFile);
const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sources = path.join(projectRoot, 'packaging', 'windows');
const ICON_SIZES = [16, 20, 24, 32, 40, 48, 64, 128, 256];

export function compilerPath() {
  return path.join(process.env.WINDIR || 'C:\\Windows', 'Microsoft.NET', 'Framework64', 'v4.0.30319', 'csc.exe');
}

// An .ico of PNG images (Windows Vista and later), crisp at every taskbar size.
async function writeIcon(build) {
  // The icons are drawn at 1024 px; below 48 px the cover scene becomes noise, so
  // those sizes show the sticker alone (icon-small.svg).
  const full = await readFile(path.join(projectRoot, 'assets', 'icon.svg'));
  const plain = await readFile(path.join(projectRoot, 'assets', 'icon-small.svg'));
  const images = [];
  for (const size of ICON_SIZES) {
    images.push(await sharp(size < 48 ? plain : full).resize(size, size).png({ compressionLevel: 9 }).toBuffer());
  }
  const header = Buffer.alloc(6 + 16 * images.length);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(images.length, 4);
  let offset = header.length;
  images.forEach((png, i) => {
    const size = ICON_SIZES[i], at = 6 + i * 16;
    header.writeUInt8(size >= 256 ? 0 : size, at);
    header.writeUInt8(size >= 256 ? 0 : size, at + 1);
    header.writeUInt16LE(1, at + 4);
    header.writeUInt16LE(32, at + 6);
    header.writeUInt32LE(png.length, at + 8);
    header.writeUInt32LE(offset, at + 12);
    offset += png.length;
  });
  await writeFile(path.join(build, 'icon.ico'), Buffer.concat([header, ...images]));
  await writeFile(path.join(build, 'icon.png'), await sharp(full).resize(128, 128).png().toBuffer());
}

// Edition constants (name, folder, id) compiled into both programs.
function productSource({ name, folder, id, exe, version, publisher, url }) {
  const numeric = String(version).split(/[.-]/).filter(p => /^\d+$/.test(p)).slice(0, 3);
  while (numeric.length < 3) numeric.push('0');
  const field = (key, value) => `    public const string ${key} = ${JSON.stringify(value)};`;
  return ['// Generated by scripts/windows-exe.js for one edition of the program.', 'static class Product', '{',
    field('Name', name), field('Folder', folder), field('Id', id), field('Exe', exe), field('DisplayVersion', version),
    field('AssemblyVersion', `${numeric.join('.')}.0`), field('Publisher', publisher), field('Url', url), '}', ''].join('\r\n');
}

export async function prepareExeBuild(build, product) {
  await writeIcon(build);
  await writeFile(path.join(build, 'Product.cs'), productSource(product), 'utf8');
  for (const file of ['Shared.cs', 'Launcher.cs', 'Setup.cs', 'app.manifest']) await copyFile(path.join(sources, file), path.join(build, file));
}

async function compile(build, out, files, { references = [], resources = [] } = {}) {
  const args = ['/nologo', '/target:winexe', '/platform:anycpu', '/optimize+', '/codepage:65001', '/warnaserror-',
    `/win32icon:${path.join(build, 'icon.ico')}`, `/win32manifest:${path.join(build, 'app.manifest')}`,
    `/resource:${path.join(build, 'icon.png')},icon.png`, ...resources.map(r => `/resource:${r.file},${r.name}`),
    '/r:System.Windows.Forms.dll', '/r:System.Drawing.dll', ...references.map(r => `/r:${r}`),
    `/out:${out}`, ...['Product.cs', ...files].map(f => path.join(build, f))];
  try { await run(compilerPath(), args, { maxBuffer: 8_000_000, windowsHide: true }); }
  catch (e) { throw new Error(`O compilador C# do Windows recusou ${path.basename(out)}:\n${e.stdout || e.message}`); }
}

export const compileLauncher = (build, out) => compile(build, out, ['Shared.cs', 'Launcher.cs']);
export const compileSetup = (build, out, payload) => compile(build, out, ['Shared.cs', 'Setup.cs'], {
  references: ['System.IO.Compression.dll', 'System.IO.Compression.FileSystem.dll'],
  resources: [{ file: payload, name: 'payload.zip' }],
});
