const appRoot = path.dirname(fileURLToPath(import.meta.url));
const SAMPLE_RATIOS = { '4x5': [4, 5], '1x1': [1, 1], '16x9': [16, 9], '3x4': [3, 4] };
const int = (v, low, high, fallback) => { const n = Number.parseInt(v, 10); return Number.isFinite(n) ? Math.min(high, Math.max(low, n)) : fallback; };
const httpError = (status, message) => Object.assign(new Error(message), { status });

export function openFolder(dir) {
  // The path is generated by the app (never by the browser), and goes as an argument.
  const child = process.platform === 'win32'
    ? spawn('explorer.exe', [dir], { detached: true, stdio: 'ignore' })
    : spawn(process.platform === 'darwin' ? 'open' : 'xdg-open', [dir], { detached: true, stdio: 'ignore' });
  child.on('error', () => {});
  child.unref();
}

// Neutral backdrop for the kit preview before the first batch exists.
function neutralSample(width, height) {
  return Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}"><defs>`
    + '<linearGradient id="a" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#3b4a5c"/><stop offset=".55" stop-color="#1c232c"/><stop offset="1" stop-color="#0f1216"/></linearGradient>'
    + '<radialGradient id="b" cx=".72" cy=".28" r=".55"><stop offset="0" stop-color="#e9b872" stop-opacity=".55"/><stop offset="1" stop-color="#e9b872" stop-opacity="0"/></radialGradient>'
    + '<radialGradient id="c" cx=".2" cy=".8" r=".6"><stop offset="0" stop-color="#4f8fd6" stop-opacity=".35"/><stop offset="1" stop-color="#4f8fd6" stop-opacity="0"/></radialGradient></defs>'
    + `<rect width="${width}" height="${height}" fill="url(#a)"/><rect width="${width}" height="${height}" fill="url(#b)"/><rect width="${width}" height="${height}" fill="url(#c)"/></svg>`);
}

export async function createApp(dataRoot, { profileRoot, open = openFolder } = {}) {
  const root = path.resolve(dataRoot);
  const temp = path.join(root, 'temp');
  await mkdir(temp, { recursive: true });
  // Uploads interrupted by a previous crash are never needed again.
  for (const f of await readdir(temp).catch(() => [])) await rm(path.join(temp, f), { force: true, recursive: true }).catch(() => {});
  const kit = await new Kit(root).load();
  const profile = await seedProfile(root, kit, profileRoot);
  const batches = await new Batches(root, kit).init();
  const pkg = JSON.parse(await readFile(path.join(appRoot, 'package.json'), 'utf8'));
  const token = randomBytes(24).toString('hex');
  const instanceId = sha256(root.toLowerCase()).slice(0, 24);
  const app = express();
  const upload = multer({ dest: temp, limits: { fileSize: 2_000_000_000, files: 3000, fields: 10, fieldSize: 4_000_000 } });
  const single = multer({ dest: temp, limits: { fileSize: 50_000_000, files: 1, fields: 5 } }).single('file');

  app.disable('x-powered-by');
  app.use((req, res, next) => {
    // Loopback only; reject DNS rebinding and cross-origin pages.
    if (!['127.0.0.1', 'localhost', '[::1]'].includes(req.hostname)) return res.status(403).json({ error: 'Acesso apenas por este computador.' });
    const origin = req.headers.origin;
    if (origin && origin !== `http://${req.headers.host}`) return res.status(403).json({ error: 'Origem não permitida.' });
    res.setHeader('Content-Security-Policy', "default-src 'self'; img-src 'self' data: blob:; style-src 'self' 'unsafe-inline'; script-src 'self'; font-src 'self'; connect-src 'self'; frame-ancestors 'none'; object-src 'none'; base-uri 'none'; form-action 'self'");
    res.setHeader('X-Content-Type-Options', 'nosniff'); res.setHeader('Referrer-Policy', 'no-referrer');
    if (req.path.startsWith('/api/') && !['GET', 'HEAD'].includes(req.method) && req.headers['x-local-token'] !== token) return res.status(403).json({ error: 'Sessão expirada. Recarregue a página.' });
    next();
  });
  app.use(express.json({ limit: '1mb' }));
  // The drop target is drawn as the store's sticker, so it uses the sticker's font.
  app.get('/fonts/selo-:weight.ttf', (req, res, next) => {
    const file = { regular: 'OpenSans-Regular.ttf', bold: 'OpenSans-Bold.ttf' }[req.params.weight];
    if (!file) return next();
    res.sendFile(path.join(appRoot, 'assets', 'fonts', file), { headers: { 'Cache-Control': 'public, max-age=86400' } });
  });
  // The framing rules of the engine, imported as they are by the framing editor.
  app.get('/js/framing.js', (_req, res) => res.sendFile(path.join(appRoot, 'lib', 'framing.js')));
  app.use(express.static(path.join(appRoot, 'public'), { index: 'index.html' }));
  const send = (res, file, options = {}) => new Promise((resolve, reject) => res.sendFile(file, { dotfiles: 'allow', ...options }, e => e && !res.headersSent ? reject(httpError(404, 'Arquivo não encontrado.')) : resolve()));
  const removeTemp = async file => { if (file?.path) await unlink(file.path).catch(() => {}); };
  const kitChanged = () => batches.emit('event', { batchId: '*', type: 'kit', data: kit.toPublic() });

  app.get('/api/health', (_req, res) => res.json({ app: 'coverbatch-studio', version: pkg.version, instanceId }));
  // Each open window holds one presence stream. When the program was started by the
  // Windows launcher, closing the last window shuts it down (see scripts/launcher.js).
  let windows = 0;
  app.get('/api/presence', (req, res) => {
    res.writeHead(200, { 'Content-Type': 'text/event-stream; charset=utf-8', 'Cache-Control': 'no-cache, no-transform', Connection: 'keep-alive' });
    res.write(': aberto\n\n');
    app.emit('presence', ++windows);
    const ping = setInterval(() => res.write(': ping\n\n'), 15000);
    req.on('close', () => { clearInterval(ping); app.emit('presence', --windows); });
  });
  let icon = null;
  app.get('/app-icon.png', async (_req, res) => {
    icon ??= await sharp(path.join(appRoot, 'assets', 'icon.svg')).resize(192, 192).png().toBuffer();
    res.type('png').set('Cache-Control', 'public, max-age=86400').send(icon);
  });
  // The help explains where the files live, in the words of this system.
  const system = { platform: process.platform, dataDir: root };
  app.get('/api/session', (_req, res) => res.json({ token, version: pkg.version, profile, kit: kit.toPublic(), batches: batches.list(), platforms: PLATFORMS, concurrency: batches.concurrency, system }));
  app.post('/api/shutdown', async (_req, res) => {
    const stop = app.get('coverbatch.stop');
    if (typeof stop !== 'function') throw httpError(409, 'Encerre pela janela do programa.');
    await batches.flush();
    res.once('finish', () => stop());
    res.json({ ok: true });
  });
  app.get('/api/profile/developer-logo.svg', async (_req, res) => {
    if (!profile?.hasDeveloperLogo) throw httpError(404, 'Sem logo do desenvolvedor.');
    await send(res, path.join(root, 'profile', 'developer-logo.svg'), { headers: { 'Content-Type': 'image/svg+xml' } });
  });

  // --- kit -------------------------------------------------------------------
  app.get('/api/kit', (_req, res) => res.json(kit.toPublic()));
  app.patch('/api/kit', async (req, res) => {
    const format = kit.data.output.format;
    const result = await kit.update(req.body ?? {});
    if (result.output.format !== format) batches.formatChanged();
    kitChanged(); res.json(result);
  });
  app.put('/api/kit/logo', single, async (req, res) => {
    try {
      if (!req.file) throw new Error('Escolha o arquivo da logo.');
      await kit.setLogo(await readFile(req.file.path), req.file.originalname);
    } finally { await removeTemp(req.file); }
    kitChanged(); res.json(kit.toPublic());
  });
  app.delete('/api/kit/logo', async (_req, res) => { await kit.removeLogo(); kitChanged(); res.json(kit.toPublic()); });
  app.put('/api/kit/sticker/:platform', single, async (req, res) => {
    try {
      if (!PLATFORMS.includes(req.params.platform)) throw new Error('Plataforma inválida.');
      if (!req.file) throw new Error('Escolha a imagem do selo.');
      await kit.setStickerImage(req.params.platform, await readFile(req.file.path), req.file.originalname);
    } finally { await removeTemp(req.file); }
    kitChanged(); res.json(kit.toPublic());
  });
  // Back to the original kit (the private profile's, or the factory settings): one section or all.
  app.post('/api/kit/restore', async (req, res) => {
    const format = kit.data.output.format;
    const result = await kit.restore(req.body?.section ?? 'all');
    if (result.output.format !== format) batches.formatChanged();
    kitChanged(); res.json(result);
  });
  app.delete('/api/kit/sticker/:platform', async (req, res) => {
    if (!PLATFORMS.includes(req.params.platform)) throw new Error('Plataforma inválida.');
    await kit.removeStickerImage(req.params.platform); kitChanged(); res.json(kit.toPublic());
  });
  app.get('/api/kit/logo.png', async (_req, res) => {
    const bytes = await kit.logoBytes();
    if (!bytes) throw httpError(404, 'O kit ainda não tem logo.');
    res.type('png').set('Cache-Control', 'no-store').send(bytes);
  });
  // The logo on a dark and on a light cover, as the compositor draws it (shadow included).
  app.get('/api/kit/logo-swatch.png', async (req, res) => {
    const bytes = await logoSwatch(await kit.assets(), { background: req.query.bg === 'light' ? '#ecebe6' : '#1d232a' });
    if (!bytes) throw httpError(404, 'O kit ainda não tem logo.');
    res.type('png').set('Cache-Control', 'no-store').send(bytes);
  });
  app.get('/api/kit/sticker.png', async (req, res) => {
    const platform = PLATFORMS.includes(req.query.platform) ? req.query.platform : 'PS4';
    const label = kit.data.sticker.labels[LABEL_KEYS.includes(req.query.label) ? req.query.label : 'immediate'];
    const height = int(req.query.h, 16, 400, 96);
    const custom = kit.data.sticker.mode === 'image' ? (await kit.assets()).images[platform] : null;
    const bytes = custom
      ? await sharp(custom.bytes).resize({ height }).png().toBuffer()
      : await renderSticker({ platform, regular: label.regular, bold: label.bold, colors: kit.data.sticker.colors[platform], width: Math.round(height * STICKER_ASPECT), height });
    res.type('png').set('Cache-Control', 'no-store').send(bytes);
  });
  app.get('/api/kit/sample.jpg', async (req, res) => {
    const [rw, rh] = SAMPLE_RATIOS[req.query.ratio] ?? SAMPLE_RATIOS['4x5'];
    const width = int(req.query.w, 120, 1200, 480), height = Math.round(width * rh / rw);
    const platform = PLATFORMS.includes(req.query.platform) ? req.query.platform : 'PS4';
    const label = LABEL_KEYS.includes(req.query.label) ? req.query.label : 'immediate';
    const source = await batches.sampleInput();
    const input = source
      ? await sharp(source, { autoOrient: true }).resize(width, height, { fit: 'cover', position: sharp.strategy.attention }).png().toBuffer()
      : await sharp(neutralSample(width, height)).png().toBuffer();
    const base = await prepareBase(input);
    const out = await composeOutput(base, { kit: { ...kit.data, output: { format: 'jpeg', quality: 88 } }, assets: await kit.assets(), platform, label });
    res.type('jpeg').set('Cache-Control', 'no-store').send(out.bytes);
  });
  app.get('/api/kit/export', async (_req, res) => {
    const file = path.join(temp, `${randomUUID()}.zip`);
    await kit.exportZip(file);
    res.download(file, 'kit-da-loja.zip', { dotfiles: 'allow' }, () => { unlink(file).catch(() => {}); });
  });
  app.post('/api/kit/import', single, async (req, res) => {
    try {
      if (!req.file) throw new Error('Escolha o ZIP do kit.');
      const format = kit.data.output.format;
      await kit.importZip(req.file.path);
      if (kit.data.output.format !== format) batches.formatChanged();
    } finally { await removeTemp(req.file); }
    kitChanged(); res.json(kit.toPublic());
  });

  // --- batches ---------------------------------------------------------------
  app.get('/api/batches', (_req, res) => res.json(batches.list()));
  app.post('/api/batches', upload.array('files', 3000), async (req, res) => {
    const files = req.files ?? [];
    if (!files.length) throw new Error('Solte um ZIP, uma pasta ou imagens.');
    let paths = [];
    try { paths = JSON.parse(req.body?.paths || '[]'); } catch { paths = []; }
    const list = files.map((f, i) => ({ path: f.path, name: typeof paths[i] === 'string' && paths[i] ? paths[i] : f.originalname }));
    const batch = await batches.create({ files: list, title: typeof req.body?.title === 'string' ? req.body.title : '' });
    res.status(201).json(batches.summary(batch));
  });
  app.get('/api/batches/:id', (req, res) => res.json(batches.publicBatch(batches.get(req.params.id))));
  app.get('/api/batches/:id/events', (req, res) => {
    const batch = batches.get(req.params.id);
    res.writeHead(200, { 'Content-Type': 'text/event-stream; charset=utf-8', 'Cache-Control': 'no-cache, no-transform', Connection: 'keep-alive' });
    const write = (type, data) => res.write(`event: ${type}\ndata: ${JSON.stringify(data)}\n\n`);
    write('snapshot', batches.publicBatch(batch));
    const listener = e => { if (e.batchId === batch.id || e.batchId === '*') write(e.type, e.data); };
    batches.on('event', listener);
    const ping = setInterval(() => res.write(': ping\n\n'), 15000);
    req.on('close', () => { clearInterval(ping); batches.off('event', listener); });
  });
  app.patch('/api/batches/:id', async (req, res) => res.json(await batches.updateBatch(req.params.id, req.body ?? {})));
  app.post('/api/batches/:id/reapply', (req, res) => res.json(batches.reapplyKit(req.params.id)));
  app.delete('/api/batches/:id', async (req, res) => { await batches.remove(req.params.id); res.json({ ok: true }); });
  app.patch('/api/batches/:id/items/:item', async (req, res) => res.json(await batches.updateItem(req.params.id, req.params.item, req.body ?? {})));
  // orig: the cover before the sticker; PS4/PS5: the results; src: the whole art, for framing.
  app.get('/api/batches/:id/items/:item/thumb/:which', async (req, res) => {
    const batch = batches.get(req.params.id), item = batches.item(batch, req.params.item);
    if (!['orig', 'src', ...PLATFORMS].includes(req.params.which)) throw httpError(404, 'Miniatura inexistente.');
    const file = req.params.which === 'src' ? await batches.sourcePreview(batch, item) : batches.pathOf(batch, 'thumbs', `${item.id}-${req.params.which}.webp`);
    res.set('Cache-Control', 'private, max-age=31536000, immutable');
    await send(res, file);
  });
  app.get('/api/batches/:id/items/:item/original', async (req, res) => {
    const batch = batches.get(req.params.id), item = batches.item(batch, req.params.item);
    await send(res, batches.pathOf(batch, 'in', item.file), { headers: { 'Cache-Control': 'private, max-age=3600' } });
  });
  app.get('/api/batches/:id/items/:item/output/:platform', async (req, res) => {
    const batch = batches.get(req.params.id), item = batches.item(batch, req.params.item);
    const output = item.outputs?.find(o => o.platform === req.params.platform);
    if (!output || item.excluded) throw httpError(404, 'Arquivo ainda não está pronto.');
    const file = batches.pathOf(batch, 'out', output.name);
    if ('download' in req.query) res.attachment(output.name);
    await send(res, file, { headers: { 'Cache-Control': 'no-store' } });
  });
  app.get('/api/batches/:id/zip', async (req, res) => {
    const { file, name } = await batches.zip(req.params.id);
    res.attachment(name);
    await send(res, file, { headers: { 'Cache-Control': 'no-store' } });
  });
  app.post('/api/batches/:id/open', (req, res) => { open(batches.outputFolder(req.params.id)); res.json({ ok: true }); });
  app.post('/api/data/open', (_req, res) => { open(root); res.json({ ok: true }); });

  app.use('/api', (_req, _res, next) => next(httpError(404, 'Rota inexistente.')));
  app.use((err, _req, res, _next) => {
    if (res.headersSent) return;
    const tooBig = err?.code === 'LIMIT_FILE_SIZE', tooMany = err?.code === 'LIMIT_FILE_COUNT';
    // The JSON parser's own errors are in English and about the request, not the person's files.
    const badRequest = err?.type === 'entity.parse.failed', hugeRequest = err?.type === 'entity.too.large';
    const message = tooBig ? 'Arquivo grande demais para importar.' : tooMany ? 'Arquivos demais de uma vez (máximo 3 mil).'
      : badRequest ? 'Pedido inválido. Recarregue a página.' : hugeRequest ? 'Pedido grande demais.' : err?.message || 'Falha local.';
    res.status(err?.status ?? (err?.code?.startsWith?.('LIMIT_') ? 413 : 400)).json({ error: message });
  });
  return { app, kit, batches, root };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { launch } = await import('./scripts/launcher.js');
  await launch({ dataRoot: process.env.COVERBATCH_DATA_DIR || path.join(appRoot, '.local-data'), firstPort: Number(process.env.PORT || 4317) });
}
